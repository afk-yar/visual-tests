  var st = {
    spinDeg: 0, spinSpeed: 1, sunAz: -74, sunEl: 14,
    clouds: 1, lights: 1, expo: 1, paused: false, time: 0
  };

  var INV2PI = 1 / (2 * Math.PI);

  /* --- атмосферный ореол вне диска (отдельным проходом по краям строк) --- */
  var SUN_X = 0, SUN_Y = 0, SUN_E = 1;

  function haloSpan(row, from, to) {
    var d = bufData, Sx = SUN_X, Sy = SUN_Y, ex = SUN_E;
    var hf = HF, pax = AX, pay = AY;
    for (var x = from; x < to; x++) {
      var i = row + x, p = i << 2;
      var fall = hf[i];
      var ndl = pax[i] * Sx + pay[i] * Sy;
      var t = (ndl + 0.35) * 1.754386;            // smoothstep(-0.35, 0.22)
      t = t < 0 ? 0 : (t > 1 ? 1 : t);
      var lit = t * t * (3 - 2 * t);
      var gI = fall * (0.055 + 1.02 * lit * lit);
      var al = gI * 1.45;
      if (al <= 0.0001) { d[p + 3] = 0; continue; }
      if (al > 1) al = 1;
      var w = (0.35 - ndl) * 2.5;                 // smoothstep(0.35, -0.05)
      w = w < 0 ? 0 : (w > 1 ? 1 : w);
      var warm = w * w * (3 - 2 * w) * lit;
      var k = gI * ex / al;
      var gr = (0.30 + 0.62 * warm) * k;
      var gg = (0.56 + 0.20 * warm) * k;
      var gb = (1.00 - 0.22 * warm) * k;
      if (gr > 0.78) { var e1 = gr - 0.78; gr = 0.78 + e1 / (1 + e1 * 1.55); }
      if (gg > 0.78) { var e2 = gg - 0.78; gg = 0.78 + e2 / (1 + e2 * 1.55); }
      if (gb > 0.78) { var e3 = gb - 0.78; gb = 0.78 + e3 / (1 + e3 * 1.55); }
      d[p] = gr * 255; d[p + 1] = gg * 255; d[p + 2] = gb * 255; d[p + 3] = al * 255;
    }
  }

  function renderGlobe() {
    var side = bufS;
    var dd = bufData;
    /* локальные ссылки на массивы — в горячем цикле дешевле замыканий */
    var pax = AX, pay = AY, paz = AZ, plon = GLON, pinv = GINV;
    var pay0 = GAY0, paty = GATY;
    var pc1 = GC1Y0, pc1t = GC1TY, pc2 = GC2Y0, pc2t = GC2TY;
    var tex = TEX, aux = AUX, clA = cloudA, clB = cloudB;

    /* --- Солнце --- */
    var az = st.sunAz * D2R, el = st.sunEl * D2R, cel = Math.cos(el);
    var Sx = cel * Math.sin(az), Sy = Math.sin(el), Sz = cel * Math.cos(az);

    // K = S × N  — для проекции градиента рельефа на восточное направление
    var Kx = Sy * NZ - Sz * NY, Ky = Sz * NX - Sx * NZ, Kz = Sx * NY - Sy * NX;
    var NS = NX * Sx + NY * Sy + NZ * Sz;

    /* --- анизотропное отражение Солнца на воде ---
       h — половинный вектор (камера смотрит вдоль -z, вектор к камере = +z);
       g1 — направление в плоскости «Солнце–камера» (вдоль него блик вытянут),
       g2 — поперёк. Отклонение нормали от h раскладывается по (g1,g2), два
       мягких лепестка дают узкую дорожку с плавным спадом вместо белого ядра. */
    var hx = Sx, hy = Sy, hz = Sz + 1;
    var hl = Math.sqrt(hx * hx + hy * hy + hz * hz);
    hl = hl > 1e-9 ? 1 / hl : 0;
    hx *= hl; hy *= hl; hz *= hl;
    var cosI = Sx * hx + Sy * hy + Sz * hz;      // угол падения в зеркальной точке
    var g1x = Sx - hx * cosI, g1y = Sy - hy * cosI, g1z = Sz - hz * cosI;
    var gl = Math.sqrt(g1x * g1x + g1y * g1y + g1z * g1z);
    if (gl < 1e-4) {                             // Солнце ровно за камерой
      g1x = 1 - hx * hx; g1y = -hx * hy; g1z = -hx * hz;
      gl = Math.sqrt(g1x * g1x + g1y * g1y + g1z * g1z);
      if (gl < 1e-9) { g1x = 0; g1y = 1; g1z = 0; gl = 1; }
    }
    gl = 1 / gl; g1x *= gl; g1y *= gl; g1z *= gl;
    var g2x = hy * g1z - hz * g1y, g2y = hz * g1x - hx * g1z, g2z = hx * g1y - hy * g1x;

    var expo = st.expo;
    // Френель по зеркальной геометрии: скользящий свет отражается сильнее
    var fres = 0.30 + 0.70 * (1 - cosI) * (1 - cosI);
    var glCore = fres * 1.35 * expo, glSheen = fres * 0.34 * expo;

    var offRad = (LON0 + 90 - st.spinDeg) * D2R;
    var cloudOff1 = (LON0 + 90 - st.spinDeg * 1.035 - st.time * 0.55) * D2R;
    var cloudOff2 = (LON0 + 90 - st.spinDeg * 0.975 + st.time * 0.4) * D2R;
    var morph = 0.5 + 0.5 * Math.sin(st.time * 0.045);
    var cw1 = 0.62 - 0.24 * morph, cw2 = 1 - cw1;

    var cloudsK = st.clouds, lightsK = st.lights;
    var sunI = 1.16 * expo;

    SUN_X = Sx; SUN_Y = Sy; SUN_E = expo;

    for (var y = 0; y < side; y++) {
      var row = y * side;
      var xa = ROW_A[y], xb = ROW_B[y], xc = ROW_C[y], xd = ROW_D[y];
      if (xb <= xa) continue;                    // строка целиком вне ореола
      if (xd <= xc) { haloSpan(row, xa, xb); continue; }
      if (xc > xa) haloSpan(row, xa, xc);        // ореол слева
      if (xb > xd) haloSpan(row, xd, xb);        // ореол справа

      for (var x = xc; x < xd; x++) {
        var i = row + x, p = i << 2;
        var ax = pax[i], ay = pay[i], az2 = paz[i];

        /* ---------- освещённость точки ---------- */
        var ndl = ax * Sx + ay * Sy + az2 * Sz;
        var t = (ndl + 0.17) * 3.5714286;        // smoothstep(-0.17, 0.11)
        t = t < 0 ? 0 : (t > 1 ? 1 : t);
        var day = t * t * (3 - 2 * t);

        /* ---------- выборка альбедо (билинейно, широта запечена) ---------- */
        var u = (plon[i] + offRad) * INV2PI;
        u -= Math.floor(u);
        var fx = u * TW - 0.5;
        var x0 = fx < 0 ? -1 : (fx | 0);
        var tx = fx - x0;
        if (x0 < 0) x0 = TW - 1;
        var x1 = x0 + 1; if (x1 >= TW) x1 = 0;
        var ty = paty[i], mtx = 1 - tx, mty = 1 - ty;
        var w00 = mtx * mty, w10 = tx * mty, w01 = mtx * ty, w11 = tx * ty;
        var i00 = pay0[i] + x0, i10 = pay0[i] + x1, i01 = i00 + TW, i11 = i10 + TW;

        var t00 = tex[i00], t10 = tex[i10], t01 = tex[i01], t11 = tex[i11];
        var aR = ((t00 & 255) * w00 + (t10 & 255) * w10 +
                  (t01 & 255) * w01 + (t11 & 255) * w11) * 0.0039216;
        var aG = (((t00 >>> 8) & 255) * w00 + ((t10 >>> 8) & 255) * w10 +
                  ((t01 >>> 8) & 255) * w01 + ((t11 >>> 8) & 255) * w11) * 0.0039216;
        var aB = (((t00 >>> 16) & 255) * w00 + ((t10 >>> 16) & 255) * w10 +
                  ((t01 >>> 16) & 255) * w01 + ((t11 >>> 16) & 255) * w11) * 0.0039216;
        var spec = ((t00 >>> 24) * w00 + (t10 >>> 24) * w10 +
                    (t01 >>> 24) * w01 + (t11 >>> 24) * w11) * 0.0039216;

        var q00 = aux[i00];
        var lightsTex = ((q00 & 255) * w00 + (aux[i10] & 255) * w10 +
                         (aux[i01] & 255) * w01 + (aux[i11] & 255) * w11) * 0.0039216;
        var gx = (((q00 >>> 8) & 255) - 128) * 0.007874;
        var gy = (((q00 >>> 16) & 255) - 128) * 0.007874;

        /* ---------- рассеянный свет с микрорельефом ---------- */
        var invCos = pinv[i];
        var sinLat = ax * NX + ay * NY + az2 * NZ;
        var eDotS = (ax * Kx + ay * Ky + az2 * Kz) * invCos;
        var nDotS = (NS - sinLat * ndl) * invCos;
        var ndlB = ndl + (gx * eDotS + gy * nDotS) * 0.55;

        var lam = (ndlB + 0.12) * 0.893;
        lam = lam < 0 ? 0 : (lam > 1 ? 1 : lam);
        var dl = lam * day;

        /* цвет солнечного света: тёплый у терминатора */
        var wq = 1 - ndl * 2.2222222;            // smoothstep(0.45, 0.0)
        wq = wq < 0 ? 0 : (wq > 1 ? 1 : wq);
        var warmth = wq * wq * (3 - 2 * wq);
        var scR = (1 + 0.30 * warmth) * sunI;
        var scG = (1 - 0.30 * warmth) * sunI;
        var scB = (1 - 0.62 * warmth) * sunI;

        /* ---------- облака: два слоя с разным сносом ---------- */
        var cu = (plon[i] + cloudOff1) * INV2PI; cu -= Math.floor(cu);
        var cfx = cu * CW - 0.5;
        var cx0 = cfx < 0 ? -1 : (cfx | 0);
        var ctx1 = cfx - cx0;
        if (cx0 < 0) cx0 = CW - 1;
        var cx1 = cx0 + 1; if (cx1 >= CW) cx1 = 0;
        var cr0 = pc1[i], cr1 = cr0 + CW, cty = pc1t[i], mcx = 1 - ctx1;
        var cA = (clA[cr0 + cx0] * mcx + clA[cr0 + cx1] * ctx1) * (1 - cty) +
                 (clA[cr1 + cx0] * mcx + clA[cr1 + cx1] * ctx1) * cty;

        var du = (plon[i] + cloudOff2) * INV2PI; du -= Math.floor(du);
        var dfx = du * C2W - 0.5;
        var dx0 = dfx < 0 ? -1 : (dfx | 0);
        var dtx = dfx - dx0;
        if (dx0 < 0) dx0 = C2W - 1;
        var dx1 = dx0 + 1; if (dx1 >= C2W) dx1 = 0;
        var dr0 = pc2[i], dr1 = dr0 + C2W, dty = pc2t[i], mdx = 1 - dtx;
        var cB = (clB[dr0 + dx0] * mdx + clB[dr0 + dx1] * dtx) * (1 - dty) +
                 (clB[dr1 + dx0] * mdx + clB[dr1 + dx1] * dtx) * dty;

        var cd = (cA * cw1 + cB * cw2) * 0.0039216 * cloudsK;
        if (cd > 1) cd = 1;
        cd *= 0.92 + 0.42 * (1 - az2);           // у лимба путь через слой длиннее
        if (cd > 1) cd = 1;

        /* ---------- поверхность ---------- */
        var shade = dl * (1 - cd * 0.5);
        var cr = aR * scR * shade;
        var cg = aG * scG * shade;
        var cb = aB * scB * shade;

        /* ---------- солнечная дорожка на воде ---------- */
        if (spec > 0.45) {
          var hn = ax * hx + ay * hy + az2 * hz;
          if (hn > 0.86) {
            var pd = ax * g1x + ay * g1y + az2 * g1z;
            var qd = ax * g2x + ay * g2y + az2 * g2z;
            var p2 = pd * pd, q2 = qd * qd;
            var sp = 0;
            var e1 = p2 * 64 + q2 * 434;         // ядро дорожки
            if (e1 < 1) { var f1 = 1 - e1; sp = f1 * f1 * f1 * glCore; }
            var e2 = p2 * 11 + q2 * 70;          // широкий мягкий шлейф
            if (e2 < 1) { var f2 = 1 - e2; sp += f2 * f2 * glSheen; }
            if (sp > 0) {
              var wet = (spec - 0.45) * 1.82;    // берега и лёд блика не дают
              if (wet > 1) wet = 1;
              var rough = 1 - cd * 0.9;
              if (rough < 0) rough = 0;
              sp *= wet * day * rough;
              cr += sp; cg += sp * 0.94; cb += sp * 0.80;
            }
          }
        }

        /* ---------- облачный слой поверх ---------- */
        if (cd > 0.004) {
          var ca = (ndl + 0.24) * 2.6315789;     // smoothstep(-0.24, 0.14)
          ca = ca < 0 ? 0 : (ca > 1 ? 1 : ca);
          var clAmb = ca * ca * (3 - 2 * ca);
          var cl = (ndlB * 0.55 + 0.45) * clAmb * sunI;
          if (cl < 0) cl = 0;
          cr += (cl * (1 + 0.22 * warmth) * 1.02 - cr) * cd;
          cg += (cl * (1 - 0.10 * warmth) * 1.01 - cg) * cd;
          cb += (cl * (1 - 0.34 * warmth) - cb) * cd;
        }

        /* ---------- ночная сторона: огни городов + пепельный свет ---------- */
        var night = 1 - day;
        if (night > 0.004) {
          var lv = lightsTex * night * lightsK * (1 - cd * 0.72) * (0.25 + 0.75 * az2);
          lv = lv * lv * 2.45;
          var ash = night * 0.018;
          cr += lv + aR * ash * 0.55;
          cg += lv * 0.62 + aG * ash * 0.8;
          cb += lv * 0.26 + aB * ash * 1.25;
        }

        /* ---------- атмосфера на диске: рассеяние к лимбу ---------- */
        var rim = 1 - az2, rim2 = rim * rim;
        var sk = ndl * 1.3 + 0.28;
        sk = sk < 0 ? 0 : (sk > 1 ? 1 : sk);
        var sc = rim2 * rim * (0.55 + 1.9 * sk);
        var s1 = (0.3 - ndl) * 2.2222222;        // smoothstep(0.3, -0.15)
        s1 = s1 < 0 ? 0 : (s1 > 1 ? 1 : s1);
        var s2 = (ndl + 0.4) * 3.3333333;        // smoothstep(-0.4, -0.1)
        s2 = s2 < 0 ? 0 : (s2 > 1 ? 1 : s2);
        var scWarm = s1 * s1 * (3 - 2 * s1) * s2 * s2 * (3 - 2 * s2);
        cr += sc * (0.26 + scWarm * 0.9) * expo;
        cg += sc * (0.46 + scWarm * 0.30) * expo;
        cb += sc * (0.95 - scWarm * 0.20) * expo;
        // общая дымка по дневной стороне
        var haze = rim2 * 0.15 * dl;
        cr += (0.34 - cr) * haze;
        cg += (0.50 - cg) * haze;
        cb += (0.78 - cb) * haze;

        /* ---------- мягкое сжатие светов и запись ---------- */
        if (cr > 0.78) { var er = cr - 0.78; cr = 0.78 + er / (1 + er * 1.55); }
        if (cg > 0.78) { var eg = cg - 0.78; cg = 0.78 + eg / (1 + eg * 1.55); }
        if (cb > 0.78) { var eb = cb - 0.78; cb = 0.78 + eb / (1 + eb * 1.55); }
        dd[p] = cr * 255; dd[p + 1] = cg * 255; dd[p + 2] = cb * 255;
        dd[p + 3] = az2 < 0.0774 ? az2 * 3294 : 255;
      }
    }
    globeCtx.putImageData(bufImg, 0, 0);
  }

