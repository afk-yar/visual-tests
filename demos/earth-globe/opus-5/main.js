  function hash3(i, j, k) {
    var n = Math.imul(i | 0, 374761393) ^ Math.imul(j | 0, 668265263) ^
            Math.imul(k | 0, 1442695041);
    n = Math.imul(n ^ (n >>> 13), 1274126177);
    return ((n ^ (n >>> 16)) >>> 0) * 2.3283064365386963e-10;
  }

  function vnoise(x, y, z) {
    var i = Math.floor(x), j = Math.floor(y), k = Math.floor(z);
    var fx = x - i, fy = y - j, fz = z - k;
    var ux = fx * fx * (3 - 2 * fx), uy = fy * fy * (3 - 2 * fy),
        uz = fz * fz * (3 - 2 * fz);
    var c000 = hash3(i, j, k), c100 = hash3(i + 1, j, k),
        c010 = hash3(i, j + 1, k), c110 = hash3(i + 1, j + 1, k),
        c001 = hash3(i, j, k + 1), c101 = hash3(i + 1, j, k + 1),
        c011 = hash3(i, j + 1, k + 1), c111 = hash3(i + 1, j + 1, k + 1);
    var x00 = c000 + (c100 - c000) * ux, x10 = c010 + (c110 - c010) * ux,
        x01 = c001 + (c101 - c001) * ux, x11 = c011 + (c111 - c011) * ux;
    var y0 = x00 + (x10 - x00) * uy, y1 = x01 + (x11 - x01) * uy;
    return y0 + (y1 - y0) * uz;
  }

  function fbm(x, y, z, oct, lac, gain) {
    var a = 0.5, f = 1, s = 0, norm = 0;
    for (var o = 0; o < oct; o++) {
      s += a * vnoise(x * f + o * 17.3, y * f - o * 9.1, z * f + o * 5.7);
      norm += a; a *= gain; f *= lac;
    }
    return s / norm;
  }

  function ridged(x, y, z, oct) {
    var a = 0.5, f = 1, s = 0, norm = 0;
    for (var o = 0; o < oct; o++) {
      var n = vnoise(x * f + o * 31.7, y * f + o * 13.3, z * f - o * 7.9);
      n = 1 - Math.abs(n * 2 - 1);
      s += a * n * n; norm += a; a *= 0.55; f *= 2.07;
    }
    return s / norm;
  }

