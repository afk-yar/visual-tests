  function rangeFactor(lon, lat) {
    var best = 0, cosL = Math.cos(lat * Math.PI / 180);
    for (var r = 0; r < RANGES.length; r++) {
      var seg = RANGES[r], w = seg[0];
      for (var i = 1; i + 3 < seg.length; i += 2) {
        var ax = seg[i], ay = seg[i + 1], bx = seg[i + 2], by = seg[i + 3];
        var dx = (bx - ax) * cosL, dy = by - ay;
        var px = (lon - ax) * cosL, py = lat - ay;
        var len2 = dx * dx + dy * dy;
        var t = len2 > 0 ? clamp01((px * dx + py * dy) / len2) : 0;
        var qx = px - dx * t, qy = py - dy * t;
        var d = Math.sqrt(qx * qx + qy * qy);
        var f = 1 - d / w;
        if (f > best) best = f;
      }
    }
    return best > 0 ? best : 0;
  }

