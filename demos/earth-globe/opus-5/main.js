  function blurWrap(src, w, h, r, passes) {
    var tmp = new Float32Array(w * h);
    var out = new Float32Array(src);
    var inv = 1 / (2 * r + 1);
    for (var p = 0; p < passes; p++) {
      for (var y = 0; y < h; y++) {
        var row = y * w, sum = 0, k;
        for (k = -r; k <= r; k++) sum += out[row + ((k % w) + w) % w];
        for (var x = 0; x < w; x++) {
          tmp[row + x] = sum * inv;
          sum -= out[row + ((x - r) % w + w) % w];
          sum += out[row + ((x + r + 1) % w + w) % w];
        }
      }
      for (var x2 = 0; x2 < w; x2++) {
        var sum2 = 0, yy;
        for (k = -r; k <= r; k++) {
          yy = k < 0 ? 0 : (k >= h ? h - 1 : k);
          sum2 += tmp[yy * w + x2];
        }
        for (var y2 = 0; y2 < h; y2++) {
          out[y2 * w + x2] = sum2 * inv;
          var ya = y2 - r; ya = ya < 0 ? 0 : ya;
          var yb = y2 + r + 1; yb = yb >= h ? h - 1 : yb;
          sum2 -= tmp[ya * w + x2];
          sum2 += tmp[yb * w + x2];
        }
      }
    }
    return out;
  }

